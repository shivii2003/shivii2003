-- Run with a controlled deployment role in a development account.
CREATE DATABASE IF NOT EXISTS ANALYTICS;
CREATE SCHEMA IF NOT EXISTS ANALYTICS.RAW;
CREATE SCHEMA IF NOT EXISTS ANALYTICS.ANALYTICS;
CREATE SCHEMA IF NOT EXISTS ANALYTICS.AUDIT;

CREATE WAREHOUSE IF NOT EXISTS INGEST_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE TABLE IF NOT EXISTS ANALYTICS.AUDIT.INGESTION_RUNS (
    RUN_ID STRING NOT NULL,
    SOURCE_NAME STRING NOT NULL,
    STARTED_AT TIMESTAMP_TZ NOT NULL,
    FINISHED_AT TIMESTAMP_TZ,
    ROW_COUNT NUMBER,
    STATUS STRING NOT NULL,
    ERROR_MESSAGE STRING
);
