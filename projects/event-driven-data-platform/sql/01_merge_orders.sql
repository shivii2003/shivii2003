-- Illustrative idempotent merge from a prepared staging relation.
-- Populate RAW.ORDER_EVENTS_STAGE from validated JSONL using COPY INTO first.
MERGE INTO RAW.ORDER_EVENTS AS target
USING (
    SELECT
        EVENT_ID, ORDER_ID, CUSTOMER_ID, EVENT_TYPE,
        AMOUNT, CURRENCY, EVENT_TIMESTAMP, INGESTED_AT, SOURCE_FILE
    FROM RAW.ORDER_EVENTS_STAGE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY EVENT_ID
        ORDER BY INGESTED_AT DESC
    ) = 1
) AS source
ON target.EVENT_ID = source.EVENT_ID
WHEN MATCHED AND source.INGESTED_AT > target.INGESTED_AT THEN UPDATE SET
    ORDER_ID = source.ORDER_ID,
    CUSTOMER_ID = source.CUSTOMER_ID,
    EVENT_TYPE = source.EVENT_TYPE,
    AMOUNT = source.AMOUNT,
    CURRENCY = source.CURRENCY,
    EVENT_TIMESTAMP = source.EVENT_TIMESTAMP,
    INGESTED_AT = source.INGESTED_AT,
    SOURCE_FILE = source.SOURCE_FILE
WHEN NOT MATCHED THEN INSERT (
    EVENT_ID, ORDER_ID, CUSTOMER_ID, EVENT_TYPE, AMOUNT,
    CURRENCY, EVENT_TIMESTAMP, INGESTED_AT, SOURCE_FILE
) VALUES (
    source.EVENT_ID, source.ORDER_ID, source.CUSTOMER_ID, source.EVENT_TYPE,
    source.AMOUNT, source.CURRENCY, source.EVENT_TIMESTAMP,
    source.INGESTED_AT, source.SOURCE_FILE
);
